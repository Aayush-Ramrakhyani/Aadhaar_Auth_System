const request = require('supertest');
const app = require('../src/app');
const captchaService = require('../src/services/captchaService');
const { verhoeffGenerate } = require('../src/utils/verhoeff');

// Generate a Verhoeff-valid 12-digit number at test time
const BASE = '23412341234';
const VALID_AADHAAR = BASE + verhoeffGenerate(BASE);
const INVALID_AADHAAR = '123456789012'; // fails Verhoeff checksum

function extractCaptchaAnswer(image) {
  const svgDecoded = Buffer.from(
    image.replace('data:image/svg+xml;base64,', ''),
    'base64'
  ).toString();
  return [...svgDecoded.matchAll(/>([A-Z0-9])</g)].map((m) => m[1]).join('');
}

async function getValidCaptcha() {
  const res = await request(app).get('/api/captcha');
  const { captchaId, image } = res.body.data;
  return { captchaId, captchaValue: extractCaptchaAnswer(image) };
}

async function requestOtp() {
  const { captchaId, captchaValue } = await getValidCaptcha();
  const res = await request(app)
    .post('/api/aadhaar/request-otp')
    .send({ aadhaar: VALID_AADHAAR, captchaId, captchaValue });
  return res;
}

describe('GET /health', () => {
  test('returns 200 with ok status', async () => {
    const res = await request(app).get('/health');
    expect(res.status).toBe(200);
    expect(res.body.data.status).toBe('ok');
  });
});

describe('GET /api/captcha', () => {
  test('generates a captcha', async () => {
    const res = await request(app).get('/api/captcha');
    expect(res.status).toBe(200);
    expect(res.body.success).toBe(true);
    expect(res.body.data).toHaveProperty('captchaId');
    expect(res.body.data).toHaveProperty('image');
  });
});

describe('POST /api/aadhaar/validate', () => {
  test('rejects missing aadhaar', async () => {
    const res = await request(app).post('/api/aadhaar/validate').send({});
    expect(res.status).toBe(400);
  });

  test('rejects invalid aadhaar (bad checksum)', async () => {
    const res = await request(app)
      .post('/api/aadhaar/validate')
      .send({ aadhaar: INVALID_AADHAAR });
    expect(res.status).toBe(400);
    expect(res.body.success).toBe(false);
  });

  test('accepts valid aadhaar', async () => {
    const res = await request(app)
      .post('/api/aadhaar/validate')
      .send({ aadhaar: VALID_AADHAAR });
    expect(res.status).toBe(200);
    expect(res.body.success).toBe(true);
  });
});

describe('POST /api/aadhaar/request-otp', () => {
  test('rejects missing captcha fields', async () => {
    const res = await request(app)
      .post('/api/aadhaar/request-otp')
      .send({ aadhaar: VALID_AADHAAR });
    expect(res.status).toBe(400);
    expect(res.body.success).toBe(false);
  });

  test('rejects wrong captcha value', async () => {
    const { captchaId } = await getValidCaptcha();
    const res = await request(app).post('/api/aadhaar/request-otp').send({
      aadhaar: VALID_AADHAAR,
      captchaId,
      captchaValue: 'WRONG',
    });
    expect(res.status).toBe(400);
    expect(res.body.error.code).toBe('CAPTCHA_INVALID');
  });

  test('rejects invalid aadhaar with valid captcha', async () => {
    const { captchaId, captchaValue } = await getValidCaptcha();
    const res = await request(app).post('/api/aadhaar/request-otp').send({
      aadhaar: INVALID_AADHAAR,
      captchaId,
      captchaValue,
    });
    expect(res.status).toBe(400);
  });

  test('succeeds with valid aadhaar and correct captcha', async () => {
    const res = await requestOtp();
    expect(res.status).toBe(200);
    expect(res.body.success).toBe(true);
    expect(res.body.data).toHaveProperty('transactionId');
  });
});

describe('POST /api/aadhaar/verify-otp', () => {
  let transactionId;

  beforeEach(async () => {
    const res = await requestOtp();
    transactionId = res.body.data?.transactionId;
    expect(transactionId).toBeDefined();
  });

  test('rejects missing fields', async () => {
    const res = await request(app).post('/api/aadhaar/verify-otp').send({});
    expect(res.status).toBe(400);
  });

  test('rejects wrong OTP', async () => {
    const res = await request(app)
      .post('/api/aadhaar/verify-otp')
      .send({ transactionId, otp: '000000' });
    expect(res.status).toBe(401);
    expect(res.body.error.code).toBe('OTP_INVALID');
  });

  test('accepts correct OTP generated by mock provider', async () => {
    const { getProvider } = require('../src/services/aadhaar');
    const otp = getProvider().getOtpForTest(transactionId);
    expect(otp).toMatch(/^\d{6}$/);
    const res = await request(app)
      .post('/api/aadhaar/verify-otp')
      .send({ transactionId, otp });
    expect(res.status).toBe(200);
    expect(res.body.data.authenticated).toBe(true);
  });
});

describe('POST /api/aadhaar/resend-otp', () => {
  let transactionId;

  beforeEach(async () => {
    const res = await requestOtp();
    transactionId = res.body.data?.transactionId;
    expect(transactionId).toBeDefined();
  });

  test('rejects missing transactionId', async () => {
    const res = await request(app).post('/api/aadhaar/resend-otp').send({});
    expect(res.status).toBe(400);
  });

  test('succeeds on first resend', async () => {
    const res = await request(app)
      .post('/api/aadhaar/resend-otp')
      .send({ transactionId });
    expect(res.status).toBe(200);
    expect(res.body.success).toBe(true);
  });

  test('enforces resend cooldown on second immediate request', async () => {
    await request(app).post('/api/aadhaar/resend-otp').send({ transactionId });
    const res = await request(app)
      .post('/api/aadhaar/resend-otp')
      .send({ transactionId });
    expect(res.status).toBe(429);
    expect(res.body.error.code).toBe('RESEND_COOLDOWN');
  });
});

describe('GET /api/aadhaar/transaction/:id', () => {
  test('returns 404 for unknown transaction', async () => {
    const res = await request(app).get('/api/aadhaar/transaction/unknown_id');
    expect(res.status).toBe(404);
  });

  test('returns OTP_SENT status after request-otp', async () => {
    const otp = await requestOtp();
    const txnId = otp.body.data.transactionId;
    const res = await request(app).get(`/api/aadhaar/transaction/${txnId}`);
    expect(res.status).toBe(200);
    expect(res.body.data.status).toBe('OTP_SENT');
  });
});

